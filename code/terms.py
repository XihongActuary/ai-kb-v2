def _slug(t, i):
    """术语表锚点：只放 ASCII，中文锚点在部分浏览器里跳转会失效。

    缩写是 ASCII 就用缩写（MSE / Gini / IPW），否则退回英文全称；
    都没有才用序号兜底，保证同一份词典每次构建出的锚点是同一个。
    """
    s = t.get("abbr") or ""
    if not re.fullmatch(r"[A-Za-z0-9 /+._-]+", s):
        s = t.get("en") or ""
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    return s or ("t%d" % i)


