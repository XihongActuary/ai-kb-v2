        f'<text x="{X(be)+10}" y="{Y(0)-10}" font-size="12" fill="{RED}" '
        f'font-weight="bold">盈亏平衡 {be:.0f} 元/件</text>',
        f'<text x="{X(0)+6}" y="{Y(gain)-8}" font-size="11" fill="{JADE}">'
