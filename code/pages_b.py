def _wrap(solve, out, why, code, links=""):
    """三个动画共用的「收个尾」区块。

    动画好看，但看完容易只记住画面、说不出所以然。这一块把四件事钉死：
    它解决什么问题 → 跑完手上多了什么 → 最终表达式怎么读 → 代码在哪、在干什么。
    数字全部来自 out/anim_facts.json（由 node code/_animfacts.js 复算动画得出）。
    """
    rows = "".join(f"<tr><td>{a}</td><td>{b}</td></tr>" for a, b in code)
    return f"""
<h2 id="wrap">收个尾：这个动画最终给出了什么</h2>
<div class="note jade"><b>它到底在解决什么问题：</b>{solve}</div>

<h4 class="sub">① 跑完之后，你手上多了什么东西</h4>
{out}

<h4 class="sub">② 最终的数学表达式，和怎么读它</h4>
{why}

<h4 class="sub">③ 代码在哪，每一段在干什么</h4>
<div class="tbl-wrap"><table class="tbl">
<tr><th>点开看代码（新窗口）</th><th>这段代码负责哪一步</th></tr>
{rows}
</table></div>
{links}
"""


